"""Writes lib/src/chat/emoji_data.dart from unicode-emoji-json.

Usage: python3 tool/emoji/generate.py path/to/data-by-group.json

The JSON comes from the unicode-emoji-json npm package (MIT), which
repackages the Unicode emoji data. Run from packages/ui_kit.
"""

import json
import sys

# Newest emoji version macOS 14 draws; later ones show as boxes.
MAX_VERSION = 15.0

GROUPS = {
    "Smileys & Emotion": "smileys",
    "People & Body": "people",
    "Animals & Nature": "animals",
    "Food & Drink": "food",
    "Travel & Places": "travel",
    "Activities": "activities",
    "Objects": "objects",
    "Symbols": "symbols",
    "Flags": "flags",
}


def dart_string(text):
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def main(path):
    groups = json.load(open(path, encoding="utf-8"))
    out = [
        "// Generated by tool/emoji/generate.py from the Unicode emoji data",
        "// (via unicode-emoji-json). Do not edit by hand.",
        "",
        "/// The emoji groups, in the order the Unicode data lists them.",
        "enum EmojiGroup {",
    ]
    out += [f"  {slug}," for slug in GROUPS.values()]
    out += [
        "}",
        "",
        "/// Every emoji macOS can draw, by group, each with its English name",
        "/// for searching.",
        "const Map<EmojiGroup, List<(String, String)>> emojiByGroup = {",
    ]
    for group in groups:
        slug = GROUPS[group["name"]]
        out.append(f"  EmojiGroup.{slug}: [")
        for emoji in group["emojis"]:
            if float(emoji["emoji_version"]) > MAX_VERSION:
                continue
            out.append(
                f"    ({dart_string(emoji['emoji'])}, "
                f"{dart_string(emoji['name'])}),"
            )
        out.append("  ],")
    out.append("};")
    target = "lib/src/chat/emoji_data.dart"
    with open(target, "w", encoding="utf-8") as file:
        file.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
